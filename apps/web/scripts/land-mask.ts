// Generates src/landing/globe/landMask.ts: which points of a Fibonacci lattice on the globe fall
// on land, from Natural Earth 1:110m land (public domain) as packaged by world-atlas (ISC).
// Run: pnpm --filter @wasit/web generate:land
import { geoContains } from "d3-geo";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import { fibonacciPoint, toLatLon } from "../src/landing/globe/geo";

const SAMPLES = 50_000;

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8"),
) as Topology<{ land: GeometryCollection }>;
const land = feature(topology, topology.objects.land);

const bits = new Uint8Array(Math.ceil(SAMPLES / 8));
let count = 0;
for (let i = 0; i < SAMPLES; i++) {
  const { lat, lon } = toLatLon(fibonacciPoint(i, SAMPLES));
  if (geoContains(land, [lon, lat])) {
    bits[i >> 3]! |= 1 << (i & 7);
    count++;
  }
}

const out = new URL("../src/landing/globe/landMask.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/land-mask.ts from Natural Earth 1:110m land. Do not edit.

/** Size of the Fibonacci lattice the mask was sampled on (see geo.ts). */
export const LAND_SAMPLES = ${SAMPLES};

/** Lattice points on land (${count} of ${SAMPLES}). */
export const LAND_COUNT = ${count};

const MASK = Uint8Array.from(
  atob(
    "${Buffer.from(bits).toString("base64")}",
  ),
  (c) => c.charCodeAt(0),
);

export const isLand = (i: number) => ((MASK[i >> 3] ?? 0) & (1 << (i & 7))) !== 0;
`,
);
console.log(
  `${count} of ${SAMPLES} lattice points on land (${((100 * count) / SAMPLES).toFixed(1)}%)`,
);
