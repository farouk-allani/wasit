/**
 * Writes src/generated/ from the forge build output and deployments/*.json, so ABIs, addresses,
 * enums and protocol constants are never copied by hand. Run after `forge build` and after every
 * deployment: pnpm --filter @wasit/sdk generate
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const repo = new URL("../../../", import.meta.url);
const target = new URL("../src/generated/", import.meta.url);
const HEADER = "// Generated by packages/sdk/scripts/generate.ts. Do not edit.\n";

interface AstNode {
  nodeType: string;
  name?: string;
  constant?: boolean;
  members?: AstNode[];
  nodes?: AstNode[];
  value?: { nodeType: string; value?: string; subdenomination?: string };
}
interface Artifact {
  abi: unknown[];
  ast: AstNode;
}

const artifact = (file: string, contract = file) =>
  JSON.parse(
    readFileSync(new URL(`contracts/out/${file}.sol/${contract}.json`, repo), "utf8"),
  ) as Artifact;

// Exported name → artifacts whose ABIs are concatenated
const ABIS: Record<string, [file: string, contract?: string][]> = {
  wasitEscrowAbi: [["WasitEscrow"]],
  advanceBondAbi: [["AdvanceBond"]],
  priceOracleAbi: [["IPriceOracle"]],
  demoOracleAbi: [["DemoOracle"]],
  swapAdapterAbi: [["ISwapAdapter"]],
  mezoRouterAbi: [["MezoRouterAdapter", "IMezoRouter"]],
  permitTokenAbi: [["IERC20Metadata"], ["IERC20Permit"]], // MUSD: ERC-20 + EIP-2612
};

function abis(): string {
  const blocks = Object.entries(ABIS).map(([name, sources]) => {
    const entries = sources.flatMap(([file, contract]) => artifact(file, contract).abi);
    const lines = entries.map((entry) => `  ${JSON.stringify(entry)},`).join("\n");
    return `export const ${name} = [\n${lines}\n] as const;\n`;
  });
  return [HEADER, ...blocks].join("\n");
}

function addresses(): string {
  const dir = new URL("deployments/", repo);
  const files = readdirSync(dir).filter((f) => f.endsWith(".json") && !f.endsWith(".dry-run.json"));
  const blocks = files.sort().map((file) => {
    const d = JSON.parse(readFileSync(new URL(file, dir), "utf8")) as Record<string, unknown>;
    const fields = Object.entries(d)
      .map(([k, v]) => `    ${k}: ${k === "deployBlock" ? `${String(v)}n` : JSON.stringify(v)},`)
      .join("\n");
    return `  ${JSON.stringify(file.replace(/\.json$/, ""))}: {\n${fields}\n  },`;
  });
  return `${HEADER}
/** Contract sets by deployment name (deployments/<name>.json). */
export const deployments = {
${blocks.join("\n")}
} as const;

export type DeploymentName = keyof typeof deployments;
`;
}

const SECONDS: Record<string, number> = { minutes: 60, hours: 3_600, days: 86_400, weeks: 604_800 };

function constants(): string {
  const out: string[] = [HEADER];
  const walk = (node: AstNode) => {
    if (node.nodeType === "EnumDefinition" && node.name && node.members) {
      const members = node.members.map((m, i) => `  ${m.name}: ${i},`).join("\n");
      out.push(`export const ${node.name} = {\n${members}\n} as const;`);
      out.push(`export type ${node.name} = (typeof ${node.name})[keyof typeof ${node.name}];\n`);
    }
    if (node.constant && node.name && node.value?.nodeType === "Literal" && node.value.value) {
      const unit = node.value.subdenomination ? (SECONDS[node.value.subdenomination] ?? 0) : 1;
      if (unit === 0) throw new Error(`unknown unit in ${node.name}`);
      const value = Number(node.value.value.replaceAll("_", "")) * unit;
      out.push(`export const ${node.name} = ${value};`);
    }
    node.nodes?.forEach(walk);
  };
  for (const name of ["WasitTypes", "WasitEscrow", "AdvanceBond"]) walk(artifact(name).ast);
  return out.join("\n") + "\n";
}

writeFileSync(new URL("abis.ts", target), abis());
writeFileSync(new URL("addresses.ts", target), addresses());
writeFileSync(new URL("constants.ts", target), constants());
console.log(`wrote ${target.pathname}{abis,addresses,constants}.ts`);
